/*
Assumptions:
1. The table name is events.
2. Each row represents one event generated by one user.
3. The event_ts column stores the timestamp when the event occurred.
4. If a user generates the same event multiple times, only the first occurrence is considered for the analysis.
5. The Save journey starts with app_opened and ends with first_unit_credited.
6. The funnel stages follow the assignment mapping:
   app_opened → mobile_otp_verified → pan_verified →
   sip_amount_confirmed → bank_account_verified →
   upi_mandate_completed → additional_details_submitted →
   investment_otp_verified → sip_created →
   first_unit_credited.

7. The events email_otp_verified and save_dashboard_viewed are intentionally excluded because they are not part of the required funnel stages.
8. The stage counts provided in the assignment are treated as reference only. All metrics are calculated from the events table.
9. The SQL is written for PostgreSQL.
*/

--Q1. Save Journey Funnel


WITH funnel AS
( SELECT
user_id,
event_name,
MIN(event_ts) AS first_time

FROM events

GROUP BY user_id, event_name ),

stage_counts AS
( SELECT
event_name,
COUNT(DISTINCT user_id) AS users
FROM funnel
WHERE event_name IN (
'app_opened',
'mobile_otp_verified',
'pan_verified',
'sip_amount_confirmed',
'bank_account_verified',
'upi_mandate_completed',
'additional_details_submitted',
'investment_otp_verified',
'sip_created',
'first_unit_credited'
)
GROUP BY event_name ),

ordered AS
( SELECT
event_name,
users,

CASE event_name

WHEN 'app_opened' THEN 1
WHEN 'mobile_otp_verified' THEN 2
WHEN 'pan_verified' THEN 3
WHEN 'sip_amount_confirmed' THEN 4
WHEN 'bank_account_verified' THEN 5
WHEN 'upi_mandate_completed' THEN 6
WHEN 'additional_details_submitted' THEN 7
WHEN 'investment_otp_verified' THEN 8
WHEN 'sip_created' THEN 9
WHEN 'first_unit_credited' THEN 10

END AS stage_order

FROM stage_counts )

SELECT
event_name,
users,
ROUND(
100.0 * users /
LAG(users) OVER (ORDER BY stage_order),
2
) AS step_conversion_percent
FROM ordered
ORDER BY stage_order;


-- Q2. Median Completion Time

WITH completed_users AS (
SELECT
user_id,
MIN(event_ts)
FILTER
(WHERE event_name='app_opened')
AS start_time,

MIN(event_ts)
FILTER
(WHERE event_name='first_unit_credited')
AS end_time
FROM events
GROUP BY user_id)

SELECT

percentile_cont(0.5)
WITHIN GROUP
( ORDER BY
end_time-start_time )

AS median_completion_time

FROM completed_users

WHERE start_time IS NOT NULL
AND end_time IS NOT NULL;


-- Q3. Largest Drop-Off


WITH funnel AS (

SELECT
event_name,
COUNT(DISTINCT user_id) AS users,

CASE event_name

WHEN 'app_opened' THEN 1
WHEN 'mobile_otp_verified' THEN 2
WHEN 'pan_verified' THEN 3
WHEN 'sip_amount_confirmed' THEN 4
WHEN 'bank_account_verified' THEN 5
WHEN 'upi_mandate_completed' THEN 6
WHEN 'additional_details_submitted' THEN 7
WHEN 'investment_otp_verified' THEN 8
WHEN 'sip_created' THEN 9
WHEN 'first_unit_credited' THEN 10

END AS stage_order

FROM events

WHERE event_name IN (
'app_opened',
'mobile_otp_verified',
'pan_verified',
'sip_amount_confirmed',
'bank_account_verified',
'upi_mandate_completed',
'additional_details_submitted',
'investment_otp_verified',
'sip_created',
'first_unit_credited'
)
GROUP BY event_name ),

dropoffs AS (

SELECT
event_name,
users,
LAG(users) OVER (ORDER BY stage_order) AS previous_users
FROM funnel
)

SELECT
event_name,
(previous_users - users) AS users_dropped

FROM dropoffs

WHERE previous_users IS NOT NULL

ORDER BY users_dropped DESC

LIMIT 1;
